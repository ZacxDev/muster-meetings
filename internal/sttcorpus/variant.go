package sttcorpus

import (
	"bytes"
	"fmt"
	"sort"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"
)

// Suffix ends a variant's file name: m01-standup.yaml's variant is
// m01-standup.stt.yaml, in the same directory.
const Suffix = ".stt.yaml"

// VariantName is the variant's file name for a source file name.
func VariantName(source string) string { return strings.TrimSuffix(source, ".yaml") + Suffix }

// IsVariant says a file name is a variant's.
func IsVariant(name string) bool { return strings.HasSuffix(name, Suffix) }

// The engines a variant may name: one of the plugin's two STT paths, or
// mixed when a nemotron run fell back to utterance for some lines.
const (
	EngineNemotron  = "nemotron"
	EngineUtterance = "utterance"
	EngineMixed     = "mixed"
)

// Info is the record a variant carries under `stt`: how its text was made,
// and how far that text is from the source's.
type Info struct {
	// Engine produced the text: nemotron, utterance, or mixed; Lines is how
	// many stored lines each engine produced.
	Engine string         `yaml:"engine"`
	Lines  map[string]int `yaml:"lines"`
	// Tool is the tool and its version ("items-corpus-stt 1").
	Tool string `yaml:"tool"`
	// Voices is each speaker's synthesised voice: "<piper model>#<speaker id>".
	Voices map[string]string `yaml:"voices"`
	// WER is the word error rate against the source text, summed per
	// segment (Errors over Words, Score.Rate); a pointer so that a missing
	// one is not read as 0.
	WER    *float64 `yaml:"wer"`
	Words  int      `yaml:"words"`
	Errors int      `yaml:"errors"`
	// AudioSeconds is the synthesised audio streamed to the engine, silence
	// included.
	AudioSeconds float64 `yaml:"audio_seconds"`
}

// Write is the variant of source (a corpus meeting's YAML): the same
// document with every segment's text replaced by texts[id] and info added
// as `stt`. Nothing else is touched (ids, speakers, labels, traps and
// comments stay as written), every segment must have a text (an empty one
// is allowed: the engine heard nothing), and texts may name no other
// segment.
func Write(source []byte, texts map[int64]string, info Info) ([]byte, error) {
	var doc yaml.Node
	if err := yaml.Unmarshal(source, &doc); err != nil {
		return nil, err
	}
	if doc.Kind != yaml.DocumentNode || len(doc.Content) != 1 || doc.Content[0].Kind != yaml.MappingNode {
		return nil, fmt.Errorf("the source is not one YAML mapping")
	}
	top := doc.Content[0]
	if value(top, "stt") != nil {
		return nil, fmt.Errorf("the source already has an stt block: it is a variant")
	}
	segs := value(top, "segments")
	if segs == nil || segs.Kind != yaml.SequenceNode {
		return nil, fmt.Errorf("the source has no segments")
	}
	used := map[int64]bool{}
	for _, s := range segs.Content {
		idn, text := value(s, "id"), value(s, "text")
		if idn == nil || text == nil {
			return nil, fmt.Errorf("line %d: a segment without an id or a text", s.Line)
		}
		id, err := strconv.ParseInt(idn.Value, 10, 64)
		if err != nil {
			return nil, fmt.Errorf("line %d: segment id %q: %w", s.Line, idn.Value, err)
		}
		t, ok := texts[id]
		if !ok {
			return nil, fmt.Errorf("segment %d has no transcript", id)
		}
		if strings.ContainsAny(t, "\r\n") {
			return nil, fmt.Errorf("segment %d's transcript has a line break", id)
		}
		used[id] = true
		text.Value, text.Tag, text.Style = t, "!!str", yaml.DoubleQuotedStyle
	}
	var extra []string
	for id := range texts {
		if !used[id] {
			extra = append(extra, strconv.FormatInt(id, 10))
		}
	}
	if len(extra) > 0 {
		sort.Strings(extra)
		return nil, fmt.Errorf("transcripts for segments not in the source: %s", strings.Join(extra, ", "))
	}
	var in yaml.Node
	if err := in.Encode(info); err != nil {
		return nil, err
	}
	key := &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: "stt",
		HeadComment: "Generated by cmd/items-corpus-stt: the source's text spoken by Piper and transcribed\nby the plugin's STT engine. Do not edit; run the tool again."}
	top.Content = append(top.Content, key, &in)
	var b bytes.Buffer
	enc := yaml.NewEncoder(&b)
	enc.SetIndent(2)
	if err := enc.Encode(&doc); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}

// value is the value of key in mapping m, or nil.
func value(m *yaml.Node, key string) *yaml.Node {
	if m.Kind != yaml.MappingNode {
		return nil
	}
	for i := 0; i+1 < len(m.Content); i += 2 {
		if m.Content[i].Value == key {
			return m.Content[i+1]
		}
	}
	return nil
}
